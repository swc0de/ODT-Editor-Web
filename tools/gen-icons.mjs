import * as L from 'lucide';
import { writeFileSync } from 'node:fs';
const CATS = {
  people: 'user users user-round baby person-standing accessibility hand heart-handshake contact smile frown laugh brain ear eye footprints',
  communication: 'mail message-circle message-square phone phone-call send megaphone bell at-sign inbox mic video rss share-2 wifi',
  business: 'briefcase building building-2 chart-bar chart-line chart-pie trending-up trending-down calculator wallet credit-card banknote coins piggy-bank handshake receipt store target award',
  education: 'book book-open graduation-cap school pencil pen notebook library microscope flask-conical atom calculator ruler globe lightbulb',
  technology: 'laptop monitor smartphone tablet cpu server database hard-drive keyboard mouse printer camera headphones cloud code wifi battery plug',
  nature: 'sun moon cloud cloud-rain cloud-snow snowflake wind leaf tree-pine trees flower flower-2 sprout mountain waves droplet flame rainbow',
  travel: 'car bus train-front plane ship bike map map-pin compass luggage tent caravan fuel traffic-cone anchor',
  food: 'coffee cup-soda wine beer pizza sandwich apple cherry carrot cake ice-cream-cone utensils chef-hat egg fish croissant',
  health: 'heart heart-pulse activity stethoscope pill syringe thermometer hospital ambulance bandage dumbbell apple',
  home: 'house home sofa bed bath lamp key door-open armchair washing-machine refrigerator microwave shower-head',
  arrows: 'arrow-up arrow-down arrow-left arrow-right arrow-up-right arrow-down-right move refresh-cw rotate-ccw undo-2 redo-2 corner-up-right chevrons-right circle-arrow-right',
  symbols: 'check x plus minus star circle square triangle hexagon diamond info circle-alert circle-help ban asterisk hash percent infinity',
  celebration: 'gift party-popper cake balloon trophy medal crown sparkles music music-2 ticket',
  security: 'lock unlock shield shield-check key fingerprint scan-face eye-off siren',
  leisure: 'gamepad-2 dice-5 puzzle palette brush camera film tv headphones guitar volleyball',
  time: 'clock alarm-clock calendar calendar-days hourglass timer watch history',
};
const pascal = (s) => s.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('');
const used = new Map();
const out = {};
for (const [cat, names] of Object.entries(CATS)) {
  out[cat] = [];
  for (const n of [...new Set(names.split(/\s+/))]) {
    const P = pascal(n);
    if (!L[P]) { console.error('missing', n); continue; }
    used.set(P, n);
    out[cat].push(n);
  }
}
const imports = [...used.keys()].sort();
const src = `/** Icons for Insert ▸ Icons: a curated set of Lucide icons (ISC licence), by category. Generated by tools/gen-icons.mjs. */
import {
${imports.map((x) => `  ${x},`).join('\n')}
} from 'lucide';

export const ICON_NODES = {
${imports.map((x) => `  '${used.get(x)}': ${x},`).join('\n')}
};

export const ICON_CATEGORIES = ${JSON.stringify(out, null, 2).replace(/"/g, "'")};
`;
writeFileSync('src/ui/icon-library.js', src);
console.log('icons', imports.length);
