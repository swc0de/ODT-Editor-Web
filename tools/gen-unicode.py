#!/usr/bin/env python3
"""Generates src/ui/unicode-data.js (Unicode blocks and character names for the Symbol dialog).

    python3 tools/gen-unicode.py
"""
import unicodedata, json

BLOCKS = [
 ('basicLatin',0x20,0x7E),('latin1',0xA0,0xFF),('latinExtA',0x100,0x17F),('latinExtB',0x180,0x24F),('ipa',0x250,0x2AF),
 ('spacingModifiers',0x2B0,0x2FF),('combining',0x300,0x36F),('greek',0x370,0x3FF),('cyrillic',0x400,0x4FF),('hebrew',0x590,0x5FF),
 ('latinExtAdditional',0x1E00,0x1EFF),('generalPunctuation',0x2000,0x206F),('superSub',0x2070,0x209F),('currency',0x20A0,0x20CF),
 ('letterlike',0x2100,0x214F),('numberForms',0x2150,0x218F),('arrows',0x2190,0x21FF),('mathOperators',0x2200,0x22FF),
 ('miscTechnical',0x2300,0x23FF),('enclosedAlphanumerics',0x2460,0x24FF),('boxDrawing',0x2500,0x257F),('blockElements',0x2580,0x259F),
 ('geometricShapes',0x25A0,0x25FF),('miscSymbols',0x2600,0x26FF),('dingbats',0x2700,0x27BF),('suppArrowsA',0x27F0,0x27FF),
 ('suppArrowsB',0x2900,0x297F),('miscMathB',0x2980,0x29FF),('suppMathOperators',0x2A00,0x2AFF),('miscSymbolsArrows',0x2B00,0x2BFF),
 ('alphabeticPresentation',0xFB00,0xFB4F),
]
blocks, names = [], []
for (bid, a, b) in BLOCKS:
    for cp in range(a, b + 1):
        try:
            names.append(f"{cp:x}:{unicodedata.name(chr(cp)).lower()}")
        except ValueError:
            pass
    blocks.append([bid, a, b])
src = "/** Unicode blocks and character names for the Symbol dialog (generated by tools/gen-unicode.py from Python's unicodedata, Unicode %s). */\nexport const UNICODE_BLOCKS = %s;\n\n/** 'hex:name' for every named character in those blocks. */\nexport const UNICODE_NAMES = %s.split('|');\n" % (unicodedata.unidata_version, json.dumps(blocks), json.dumps('|'.join(names)))
open('src/ui/unicode-data.js', 'w').write(src)
print(len(names), 'names')
